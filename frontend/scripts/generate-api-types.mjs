#!/usr/bin/env node
/**
 * Generate TypeScript types from the backend OpenAPI schema.
 *
 * Zero-dependency generator (drop-in replacement for `openapi-typescript`,
 * which cannot be installed offline).  Reads `backend/openapi.json` (exported
 * by `backend/scripts/export_openapi.py`) and writes `lib/api.generated.d.ts`.
 *
 * Run:  node scripts/generate-api-types.mjs   (from frontend/)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const FRONTEND_ROOT = resolve(SCRIPT_DIR, "..");
const OPENAPI_PATH = resolve(FRONTEND_ROOT, "../backend/openapi.json");
const OUT_PATH = resolve(FRONTEND_ROOT, "lib/api.generated.d.ts");

const spec = JSON.parse(readFileSync(OPENAPI_PATH, "utf8"));
const schemas = spec.components?.schemas ?? {};

const TS_RESERVED = new Set([
  "string", "number", "boolean", "object", "any", "unknown", "never",
  "void", "null", "undefined", "bigint", "symbol", "Record", "Array",
]);

function tsTypeName(name) {
  if (TS_RESERVED.has(name)) return `"${name}"`; // never hit for schemas
  return name;
}

function toTs(schema, depth = 0) {
  if (schema == null) return "unknown";
  if (Object.prototype.hasOwnProperty.call(schema, "const")) {
    return JSON.stringify(schema.const);
  }
  if (schema.$ref) {
    const name = schema.$ref.split("/").pop();
    return `ApiSchemas["${name}"]`;
  }
  if (schema.anyOf) {
    const parts = schema.anyOf.map((s) => toTs(s, depth + 1));
    const withoutNull = parts.filter((p) => p !== "null");
    if (withoutNull.length === parts.length) {
      return parts.length === 1 ? parts[0] : `(${parts.join(" | ")})`;
    }
    const base = withoutNull.length === 1 ? withoutNull[0] : `(${withoutNull.join(" | ")})`;
    return `${base} | null`;
  }
  if (schema.oneOf) {
    return `(${schema.oneOf.map((s) => toTs(s, depth + 1)).join(" | ")})`;
  }
  if (schema.allOf) {
    return schema.allOf.map((s) => toTs(s, depth + 1)).join(" & ");
  }
  if (schema.type === "array") {
    return `Array<${toTs(schema.items, depth + 1)}>`;
  }
  if (schema.enum) {
    return schema.enum
      .map((v) => (typeof v === "string" ? JSON.stringify(v) : String(v)))
      .join(" | ");
  }
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "object": {
      if (schema.additionalProperties === true || schema.additionalProperties === undefined && !schema.properties) {
        return "Record<string, unknown>";
      }
      if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
        return `Record<string, ${toTs(schema.additionalProperties, depth + 1)}>`;
      }
      if (!schema.properties) return "Record<string, unknown>";
      const required = new Set(schema.required ?? []);
      const lines = Object.entries(schema.properties).map(([key, prop]) => {
        const optional = required.has(key) ? "" : "?";
        const propName = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
        return `    ${propName}${optional}: ${toTs(prop, depth + 1)};`;
      });
      return `{\n${lines.join("\n")}\n  }`;
    }
    default:
      return "unknown";
  }
}

const lines = [
  "// Generated by scripts/generate-api-types.mjs from backend/openapi.json.",
  "// DO NOT EDIT BY HAND — run `npm run generate:types` after backend schema changes.",
  "",
  "export interface ApiSchemas {",
];

for (const [name, schema] of Object.entries(schemas)) {
  lines.push(`  ${tsTypeName(name)}: ${toTs(schema, 1)};`);
}
lines.push("}");
lines.push("");

writeFileSync(OUT_PATH, lines.join("\n"), "utf8");
console.log(`wrote ${OUT_PATH} (${Object.keys(schemas).length} schemas)`);
